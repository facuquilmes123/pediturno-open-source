// Helper to convert hex to HSL string
function hexToHsl(hex: string): string {
    // Remove hash and handle shorthand hex codes
    let sanitizedHex = hex.startsWith('#') ? hex.slice(1) : hex;
    if (sanitizedHex.length === 3) {
        sanitizedHex = sanitizedHex.split('').map(char => char + char).join('');
    }
    
    let r = parseInt(sanitizedHex.substring(0, 2), 16);
    let g = parseInt(sanitizedHex.substring(2, 4), 16);
    let b = parseInt(sanitizedHex.substring(4, 6), 16);

    r /= 255;
    g /= 255;
    b /= 255;
    
    const max = Math.max(r, g, b), min = Math.min(r, g, b);
    let h = 0, s = 0, l = (max + min) / 2;

    if (max !== min) {
        const d = max - min;
        s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
        switch(max) {
            case r: h = (g - b) / d + (g < b ? 6 : 0); break;
            case g: h = (b - r) / d + 2; break;
            case b: h = (r - g) / d + 4; break;
        }
        h /= 6;
    }

    return `${(h * 360).toFixed(0)} ${(s * 100).toFixed(0)}% ${(l * 100).toFixed(0)}%`;
}

export function generateCustomThemeCss(customTheme: CustomThemeData): { [key: string]: string } {
    const primaryHsl = hexToHsl(customTheme.primary);
    const backgroundHsl = hexToHsl(customTheme.background);
    const accentHsl = hexToHsl(customTheme.accent);

    return {
        '--background': backgroundHsl,
        '--foreground': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 20%)`, // Derived
        '--card': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 100%)`, // Derived
        '--card-foreground': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 20%)`, // Derived
        '--popover': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 100%)`, // Derived
        '--popover-foreground': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 20%)`, // Derived
        '--primary': primaryHsl,
        '--primary-foreground': '0 0% 100%', // Assume white for contrast
        '--secondary': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 92%)`, // Derived
        '--secondary-foreground': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 20%)`, // Derived
        '--muted': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 92%)`, // Derived
        '--muted-foreground': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 45%)`, // Derived
        '--accent': accentHsl,
        '--accent-foreground': '0 0% 100%', // Assume white for contrast
        '--destructive': '0 84.2% 60.2%',
        '--destructive-foreground': '0 0% 98%',
        '--border': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 88%)`, // Derived
        '--input': `hsl(${backgroundHsl.split(' ')[0]}, 10%, 88%)`, // Derived
        '--ring': primaryHsl,
    };
}


export const ThemeStyle: React.FC<ThemeStyleProps> = ({ theme, customTheme }) => {
    let themeVariables: { [key: string]: string } | null = null;
    
    if (theme) {
        themeVariables = theme;
    } else if (customTheme) {
        themeVariables = generateCustomThemeCss(customTheme);
    } else {
        return null; // or a default theme
    }

  const css = `
    :root {
      ${Object.entries(themeVariables)
        .map(([key, value]) => `${key}: ${value};`)
        .join('\n')}
    }
  `;
  return <style>{css}</style>;
};
